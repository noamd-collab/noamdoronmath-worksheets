export interface TopicPageLink {
  href?: string;
  path?: string;
  label: string;
  productionHref?: string;
}

export interface TopicPageBlock {
  type: 'paragraph' | 'list' | 'image';
  text?: string;
  links?: TopicPageLink[];
  ordered?: boolean;
  items?: string[];
  src?: string;
  alt?: string;
  width?: number | null;
  height?: number | null;
  role?: string;
}

export interface TopicPageSection {
  heading: string | null;
  blocks: TopicPageBlock[];
}

export interface TopicPageFaqItem {
  question: string;
  answer: string;
}

export interface TopicPageFaqGroup {
  heading: string;
  source?: string;
  items: TopicPageFaqItem[];
}

export interface TopicPageCatalogCta {
  label: string;
  href: string;
  source: string;
  productionHref?: string | null;
  catalogTopicId?: number | null;
  catalogTopicTitle?: string | null;
}

/** Ordered pedagogical body after H1 (intro / headings / paragraphs / CTAs). */
export type TopicBodyFlowItem =
  | { type: 'paragraph'; text: string; role?: 'intro' | 'self-check' | 'body' }
  | { type: 'heading'; text: string }
  | {
      type: 'cta';
      label: string;
      href: string;
      catalogTopicId?: number | null;
    }
  | { type: 'list'; ordered?: boolean; items: string[] };

export interface TopicPageContent {
  slug: TopicPageSlug | string;
  path: string;
  grade: number;
  sourceUrl: string;
  fetchedAt: string;
  verifiedVia?: string;
  title: string;
  description: string;
  ogImage?: string | null;
  h1: string;
  intro: string;
  sections: TopicPageSection[];
  /**
   * Source DOM order of intro/headings/paragraphs/CTAs after H1.
   * When absent, synthesized as intro → CTAs → sections (legacy default).
   */
  bodyFlow?: TopicBodyFlowItem[];
  /** Visible “נועם דורון מתמטיקה · עודכן …” line from production (null if absent on source). */
  updatedLine: string | null;
  /** Where the update line sits relative to FAQ groups (production DOM order). */
  updatedLinePlacement: 'after-sections' | 'after-first-faq-group' | 'absent';
  faqHeading: string;
  /** Flattened visible FAQ items (all groups). */
  faq: TopicPageFaqItem[];
  /** One or more visible FAQ groups (signed-numbers has two on production). */
  faqGroups: TopicPageFaqGroup[];
  author: {
    text: string;
    links: { href: string; label: string }[];
  };
  relatedTopics: { path: string; label: string; productionHref: string }[];
  /**
   * Captured production related links, before family classification.
   * Parity compares these; TopicPage renders relatedTopics.
   */
  sourceRelatedTopics?: { path: string; label: string; productionHref: string }[];
  /** First worksheet CTA (DOM order); prefer catalogCtas when multiple. */
  catalogCta: TopicPageCatalogCta;
  /** All worksheet CTAs in production DOM order. */
  catalogCtas: TopicPageCatalogCta[];
  /**
   * Worksheet CTAs that appear before the H1 on production (live DOM order).
   * When set, TopicPage renders these above the H1; they stay out of bodyFlow.
   * Generic model — no route-specific hardcoding.
   */
  preH1Ctas?: TopicPageCatalogCta[];
  gradeHubHref: string;
  jsonLd: Record<string, unknown>;
  terms: { label: string; href: string };
  images?: { src: string; alt: string; role?: string }[];
}

