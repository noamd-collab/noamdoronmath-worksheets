export function extractJsonLdFaq(
  jsonLd: Record<string, unknown>
): TopicPageFaqItem[] {
  const graph = (jsonLd['@graph'] as Record<string, unknown>[] | undefined) || [];
  const out: TopicPageFaqItem[] = [];
  for (const node of graph) {
    if (node['@type'] !== 'FAQPage') continue;
    const entities = (node.mainEntity as Record<string, unknown>[] | undefined) || [];
    for (const q of entities) {
      const answer = q.acceptedAnswer as Record<string, unknown> | undefined;
      out.push({
        question: String(q.name || ''),
        answer: String(answer?.text || ''),
      });
    }
  }
  return out;
}
