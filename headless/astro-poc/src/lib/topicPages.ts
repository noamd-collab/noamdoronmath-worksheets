export function loadTopicPage(slug: string): TopicPageContent {
  const data = BY_SLUG[slug];
  if (!data) throw new Error(`Unknown topic page slug: ${slug}`);
  if (!data.h1 || !data.title || !data.description || !data.intro) {
    throw new Error(`Topic page ${slug}: missing SEO/copy fields`);
  }
  if (data.intro.trim() === data.h1.trim()) {
    throw new Error(`Topic page ${slug}: intro must not echo H1 (capture failed)`);
  }
  if (data.intro.length < 40) {
    throw new Error(`Topic page ${slug}: intro too short`);
  }
  if (!Array.isArray(data.sections) || data.sections.length < 1) {
    throw new Error(`Topic page ${slug}: missing pedagogical sections`);
  }
  const paraCount = data.sections.reduce(
    (n, s) => n + s.blocks.filter((b) => b.type === 'paragraph' && (b.text || '').length > 8).length,
    0
  );
  if (paraCount < 2) {
    throw new Error(`Topic page ${slug}: too few educational paragraphs (${paraCount})`);
  }
  if (!hasSelfCheckSection(data.sections) && !bodyFlowHasSelfCheck(synthesizeBodyFlow(data))) {
    throw new Error(`Topic page ${slug}: missing self-check section`);
  }
  if (!Array.isArray(data.faqGroups) || data.faqGroups.length < 1) {
    throw new Error(`Topic page ${slug}: missing faqGroups`);
  }
  const flatFromGroups = data.faqGroups.flatMap((g) => g.items);
  if (flatFromGroups.length < 2) {
    throw new Error(`Topic page ${slug}: missing FAQ items`);
  }
  if (data.updatedLine != null && data.updatedLine !== '' && !data.updatedLine.includes('עודכן')) {
    throw new Error(`Topic page ${slug}: invalid updatedLine`);
  }
  if (
    data.updatedLinePlacement !== 'after-sections' &&
    data.updatedLinePlacement !== 'after-first-faq-group' &&
    data.updatedLinePlacement !== 'absent'
  ) {
    throw new Error(`Topic page ${slug}: invalid updatedLinePlacement`);
  }
  if (data.updatedLinePlacement === 'absent' && data.updatedLine) {
    throw new Error(`Topic page ${slug}: placement absent but updatedLine set`);
  }
  if (data.updatedLinePlacement !== 'absent' && !data.updatedLine) {
    throw new Error(`Topic page ${slug}: missing production updatedLine`);
  }
  const ldFaq = extractJsonLdFaq(data.jsonLd);
  if (ldFaq.length < 1) {
    throw new Error(`Topic page ${slug}: missing JSON-LD FAQ entities`);
  }
  // Strict: every FAQPage JSON-LD Q&A must appear in visible FAQ groups.
  // Do not soften globally for production-inconsistent pages — leave those unmigrated.
  for (const item of ldFaq) {
    const found = flatFromGroups.some(
      (v) => v.question === item.question && v.answer === item.answer
    );
    if (!found) {
      throw new Error(
        `Topic page ${slug}: JSON-LD FAQ not present in visible groups: ${item.question}`
      );
    }
  }
  if (!Array.isArray(data.catalogCtas) || data.catalogCtas.length < 1) {
    throw new Error(`Topic page ${slug}: missing catalogCtas`);
  }
  for (const cta of data.catalogCtas) {
    if (!cta.href?.startsWith('/worksheets?grade=')) {
      throw new Error(`Topic page ${slug}: catalog CTA must be same-origin worksheets: ${cta.href}`);
    }
  }
  if (data.catalogCta?.href !== data.catalogCtas[0].href) {
    throw new Error(`Topic page ${slug}: catalogCta must equal catalogCtas[0]`);
  }
  for (const rel of data.relatedTopics || []) {
    if (!rel.productionHref?.startsWith('https://www.noamdoronmath.co.il/')) {
      throw new Error(`Topic page ${slug}: related topic must stay on production: ${rel.path}`);
    }
  }
  if (!data.jsonLd) {
    throw new Error(`Topic page ${slug}: missing JSON-LD`);
  }
  return withVisibleMathIsolates(data);
}

export function loadAllTopicPages(): TopicPageContent[] {
  return TOPIC_PAGE_SLUGS.map(loadTopicPage);
}

