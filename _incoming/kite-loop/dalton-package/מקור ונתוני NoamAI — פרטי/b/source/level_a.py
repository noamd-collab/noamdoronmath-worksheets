def rot(pts, deg):
    t = math.radians(deg)
    c, s = math.cos(t), math.sin(t)
    return dict((n, (round(x * c - y * s, 6), round(x * s + y * c, 6)))
                for n, (x, y) in pts.items())


def kite(p, h, q, deg=0.0, names="ABCD", o=None, extra=None):
    u"""head names[0] at (-p, 0), side names[1] at (0, h), head names[2] at
    (q, 0), side names[3] at (0, -h); the diagonals meet at the origin."""
    a, b, c, d = names
    pts = {a: (-p, 0.0), b: (0.0, h), c: (q, 0.0), d: (0.0, -h)}
    if o:
        pts[o] = (0.0, 0.0)
    pts.update(extra or {})
    return rot(pts, deg)


def fig(points, fam, polygons=("ABCD",), segments=(), ticks=(), right=(),
        labels=(), size=190, prefer=None, arcs=(), dots=()):
    spec = dict(points=dict(points), polygons=list(polygons),
                segments=list(segments), ticks=[list(t) for t in ticks],
                right=list(right), labels=[list(x) for x in labels],
                fam=fam, size=size, prefer=dict(prefer or {}))
    if dots:
        spec["dots"] = list(dots)
    if arcs:
        spec["arcs"] = [list(x) for x in arcs]
        groups = {}
        for a, n in arcs:
            groups.setdefault(n, []).append(a)
        spec["equal_arcs"] = [g for g in groups.values() if len(g) > 1]
    src = DRAW_SRC + u"svg = kdraw(%r)\n" % (spec,)
    with export.replay(src):
        return _NS["kdraw"](spec)


# ------------------------------------------------------------ relations --
def sh(kind, pts):
    return dict(type="shape", points=list(pts), value=kind)


def seg(s):
    return dict(type="segment", of=s)


def eq(*ss):
    return dict(type="equal_length", of=list(ss))


def perp(a, b):
    return dict(type="perpendicular", of=[a, b])


def mid(p, s):
    return dict(type="midpoint", point=p, of=list(s))


def ln(s, v):
    return dict(type="length", of=s, value=v)


def an(s, v):
    return dict(type="angle", at=s[1], rays=[s[0], s[2]], value=v)


def col(s):
    return dict(type="collinear", points=list(s))


def aeq(a, b):
    return dict(type="equal_angle", of=[a, b])


def poly(s):
    return dict(type="polygon", points=list(s))


CM, CM2, DEG = u"ס״מ", u"סמ״ר", u"מעלות"
MT, MT2 = u"מ׳", u"מ״ר"


def F(s, v, unit=CM):
    return fd("length", of=s, value=str(v), unit=unit)


def A(s, v):
    return fd("angle", of=s, value=str(v), unit=DEG)


def Area(s, v, unit=CM2):
    return fd("area", of=s, value=str(v), unit=unit)


def Per(s, v, unit=CM):
    return fd("perimeter", of=s, value=str(v), unit=unit)


def kite_given(n):
    a, b, c, d = n
    return [sh("kite", n), eq(a + b, a + d), eq(c + b, c + d)]


def kite_ticks(n):
    a, b, c, d = n
    return [(a + b, 1), (a + d, 1), (c + b, 2), (c + d, 2)]


def words(q, constraints, room=200):
    u"""a drawing-from-words question: no figure; the conditions belong to
    the objects the student draws, and the last item keeps the blank room"""
    q["to_construct"] = list(constraints)
    q["given"] = []
    q["items"][-1]["space"] = room
    return q


def hdeg(x):
    return math.tan(math.radians(x))


