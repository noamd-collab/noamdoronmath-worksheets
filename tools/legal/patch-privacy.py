def find_text(text):
    for i, x in enumerate(b):
        if x.get('text') == text:
            return i
    raise SystemExit('missing text: ' + text)


def find_item(needle):
    for i, x in enumerate(b):
        for j, item in enumerate(x.get('items') or []):
            if needle in item.get('text', ''):
                return i, j
    raise SystemExit('missing item: ' + needle)


