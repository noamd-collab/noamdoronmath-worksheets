/**
 * Builds the payment-related legal pages from one source of truth.
 *
 * Writes:
 *   src/data/site-pages/terms.json
 *   src/data/site-pages/authoritative/terms-legal.html
 *   src/data/site-pages/purchase-terms.json
 *   src/data/site-pages/cancellation.json
 *   src/data/site-pages/delivery.json
 *
 * Usage:
 *   node tools/legal/build-legal-content.mjs           # write
 *   node tools/legal/build-legal-content.mjs --check   # fail if a file is stale
 *
 * The terms page is rendered from terms.json, while terms-legal.html is the
 * authoritative sheet kept in parity by tests/terms-legal-parity.test.ts.
 * Both are generated here from the same block list, so they cannot drift.
 */
