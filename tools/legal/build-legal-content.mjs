/* ---------------------------------------------------------------- helpers */

const p = (text, segments) => (segments ? { type: 'p', text, segments } : { type: 'p', text });
const h2 = (text) => ({ type: 'h2', text });
const ul = (items) => ({ type: 'ul', items: items.map((text) => ({ text })) });
const a = (text, href) => ({ type: 'a', text, href });

const withLinks = (parts) => {
  // parts: array of strings or {text, href}
  const segments = parts.map((part) =>
    typeof part === 'string' ? { type: 'text', text: part } : { type: 'a', text: part.text, href: part.href }
  );
  return { type: 'p', text: segments.map((s) => s.text).join(''), segments };
};

const page = (slug, title, description, h1, blocks) => ({
  slug,
  title,
  description,
  h1,
  intro: [description],
  blocks,
  source: { liveUrl: `${SITE}/${slug}`, capturedAt: '2026-11-24' },
});

