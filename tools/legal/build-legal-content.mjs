/* --------------------------------------------------------------- rendering */

const escapeHtml = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function blockHtml(block) {
  if (block.type === 'h2') return `  <h2>${escapeHtml(block.text)}</h2>`;
  if (block.type === 'ul' || block.type === 'ol') {
    const items = block.items
      .map((item) => {
        if (item.href) {
          throw new Error('List items must not carry links: the parity test only reads links from paragraphs');
        }
        return `    <li>${escapeHtml(item.text)}</li>`;
      })
      .join('\n');
    return `  <${block.type}>\n${items}\n  </${block.type}>`;
  }
  if (block.type === 'p') {
    if (block.segments?.length) {
      const inner = block.segments
        .map((seg) =>
          seg.type === 'a'
            ? `<a href="${seg.href}"${seg.href.startsWith('http') ? ' target="_blank" rel="noopener"' : ''}>${escapeHtml(seg.text)}</a>`
            : escapeHtml(seg.text)
        )
        .join('');
      return `  <p>${inner}</p>`;
    }
    return `  <p>${escapeHtml(block.text)}</p>`;
  }
  throw new Error(`Unsupported block type: ${block.type}`);
}

function termsHtml() {
  const head = readFileSync(join(PAGES, 'authoritative/terms-legal.html'), 'utf8');
  const beforeSheet = head.slice(0, head.indexOf('<div class="sheet">') + '<div class="sheet">'.length);
  const body = termsBlocks.map(blockHtml).join('\n');
  const sheetBody = body
    .replace('<p>עודכן לאחרונה: 24 בנובמבר 2026</p>', '<p class="updated">עודכן לאחרונה: 24 בנובמבר 2026</p>')
    .replace(
      '<p>כל הזכויות שמורות לנועם דורון © · דפי העבודה החינמיים יישארו חינם.</p>',
      '<p class="foot">כל הזכויות שמורות לנועם דורון © · דפי העבודה החינמיים יישארו חינם.</p>'
    );
  return `${beforeSheet}\n  <h1>${escapeHtml(terms.h1)}</h1>\n${sheetBody}\n</div>\n</body>\n</html>\n`;
}

